# Arithmatic operators in python

a = 10
b = 2

print(a, " + ", b, " = ", a + b)
print(a, " - ", b, " = ", a - b)
print(a, " * ", b, " = ", a * b)
print(a, " / ", b, " = ", a / b)
print(a, " // ", b, " = ", a // b)
print(a, " % ", b, " = ", a % b)
print(a, " ** ", b, " = ", a**b)

# Conditional operator

print(a > 4)
print(a < 11)
print(a <= 10)
print(a >= 10)
print(a == 12)
print(a != 12)

# ? Logical operators

print(True and False)
print(True or False)
print(not (False))

# Assignment operator
a = 10
print(a)
a += 2
print(a)
